//    отдельных целей.
//  · «по городу» (at) — сегменты, где угроза адресована именно этому месту:
//    «курсом на», «подлетает», «будет громко». Отличает удар по городу от пролёта мимо.
//  · «взрывы/ПВО» (hits) — сегменты со взрывом, попаданием, сбитием, пожаром.
//    Самая узкая и самая надёжная метрика.
//
