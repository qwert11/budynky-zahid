const OBLFORM = new RegExp(Object.values(OBL).join('|') + '|' + LET + '+ск(?:ий|ого|ом|ому)\\s*район|' + LET + '+ськ(?:ий|ого|ому)\\s*район', 'gi');

const CITY_INFO = {};
